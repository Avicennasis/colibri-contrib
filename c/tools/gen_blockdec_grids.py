#!/usr/bin/env python3
"""ggml_grids.h's codebooks as GLSL constants for shaders/blockdec.glsl (written to
shaders/blockdec_grids.glsl): the same bytes the CPU decoders read, 8-byte rows as
uvec2 and 4-byte rows as uint, little-endian."""
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent.parent
src = (HERE / "ggml_grids.h").read_text()


def array(name):
    m = re.search(r"static const (u?int8_t) " + name + r"\[(\d+)\] = \{(.*?)\};", src, re.S)
    if not m:
        sys.exit(f"{name} not found in ggml_grids.h")
    vals = [int(v, 0) for v in re.findall(r"-?0x[0-9a-fA-F]+|-?\d+", m.group(3))]
    assert len(vals) == int(m.group(2)), (name, len(vals))
    return [v & 0xFF for v in vals]


def words(b, width):
    out = []
    for i in range(0, len(b), 4):
        out.append(b[i] | b[i + 1] << 8 | b[i + 2] << 16 | b[i + 3] << 24)
    if width == 8:
        return [f"uvec2(0x{out[i]:08x}u,0x{out[i + 1]:08x}u)" for i in range(0, len(out), 2)]
    return [f"0x{w:08x}u" for w in out]


lines = ["// Generated by tools/gen_blockdec_grids.py from ggml_grids.h: do not edit.",
         "#ifndef BLOCKDEC_GRIDS", "#define BLOCKDEC_GRIDS"]
for name, glsl, width in (("GGML_IQ2XXS_GRID", "BD_IQ2XXS", 8), ("GGML_IQ2XS_GRID", "BD_IQ2XS", 8),
                          ("GGML_IQ2S_GRID", "BD_IQ2S", 8), ("GGML_IQ3XXS_GRID", "BD_IQ3XXS", 4),
                          ("GGML_IQ3S_GRID", "BD_IQ3S", 4), ("GGML_IQ1S_GRID", "BD_IQ1S", 8)):
    w = words(array(name), width)
    typ = "uvec2" if width == 8 else "uint"
    lines.append(f"const {typ} {glsl}[{len(w)}] = {typ}[{len(w)}](")
    lines += ["    " + ",".join(w[i:i + 4]) + ("," if i + 4 < len(w) else "") for i in range(0, len(w), 4)]
    lines.append(");")
ks = array("GGML_KSIGNS_IQ2XS")
lines.append(f"const uint BD_KSIGNS[128] = uint[128](" + ",".join(f"{v}u" for v in ks) + ");")
lines.append("const int BD_KV_IQ4NL[16] = int[16](-127,-104,-83,-65,-49,-35,-22,-10,1,13,25,38,53,69,89,113);")
lines.append("const int BD_KV_MXFP4[16] = int[16](0,1,2,3,4,6,8,12,0,-1,-2,-3,-4,-6,-8,-12);")
lines.append("#endif")
(HERE / "shaders" / "blockdec_grids.glsl").write_text("\n".join(lines) + "\n")
print("shaders/blockdec_grids.glsl:", sum(1 for _ in lines), "lines")
